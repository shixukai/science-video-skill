def execute(c,r,config_sha):
 # inner returns/raises only after its lock contexts close, unless it is holding
 # an unknown POST. This is completion of runner work, NOT an OS process-exit claim.
 lifecycle={}
 try:return execute_inner(c,r,config_sha,lifecycle)
 finally:
  root=Path(c['candidate_root'])
  outcome=root/'technical-test-one-shot-outcome.json';failed=root/'pre_submit_failure.json'
  if lifecycle.get('claimed') is True and lifecycle.get('common') is not None and lifecycle['common'].released and (outcome.exists() or failed.exists()):
   result=json.loads((outcome if outcome.exists() else failed).read_text())
   if result.get('post_started') is False or (root/'terminal.json').exists():
    save_matching(root/'runner-completion.json',{'state':'runner_work_completed_locks_released','locks_released':True,'holder_pid':os.getpid(),'post_started':result.get('post_started'),'config_sha256':config_sha,'process_exit_claimed':False})

