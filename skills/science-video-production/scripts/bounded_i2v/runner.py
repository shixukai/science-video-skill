class CommonLock:
 def __init__(self,path):self.path=path;self.released=False
 def __enter__(self):
  import ctypes
  from ctypes import wintypes
  need(not self.path.is_symlink() and not any(p.is_symlink() for p in self.path.parents),'lock path redirected')
  k=ctypes.WinDLL('kernel32',use_last_error=True);k.CreateFileW.argtypes=[wintypes.LPCWSTR,wintypes.DWORD,wintypes.DWORD,ctypes.c_void_p,wintypes.DWORD,wintypes.DWORD,wintypes.HANDLE];k.CreateFileW.restype=wintypes.HANDLE;k.CloseHandle.argtypes=[wintypes.HANDLE];k.CloseHandle.restype=wintypes.BOOL
  self.h=k.CreateFileW(str(self.path),0xC0000000,0,None,4,0x80,None);need(self.h not in (None,ctypes.c_void_p(-1).value),'shared GPU lock unavailable');self.k=k;return self
 def __exit__(self,*args):
  need(self.k.CloseHandle(self.h),'shared lock close failed');self.released=True

def terminal(g,result,root,c,bsha):
 """Unknown/accepted GPU work keeps the common lock. Never timeout-and-release."""
 if result.get('post_started') is False:return
 if result.get('state')!='accepted_unreviewed':
  try:save(root/'reconciliation-required.json',{'state':'unknown_POST_no_retry_lock_held','outcome':result})
  except Exception as e:print(json.dumps({'state':'unknown_POST_lock_held_log_write_failed','error':str(e)}),flush=True)
  while True:time.sleep(30)
 prompt=result['prompt_id'];attempt=json.loads((root/g.ATTEMPT).read_text())
 while True:
  try:
   h=g.request_local('GET','/history/'+prompt).get(prompt);q=g.request_local('GET','/queue')
   need(isinstance(q.get('queue_running'),list) and isinstance(q.get('queue_pending'),list),'queue malformed')
   rows=q['queue_running']+q['queue_pending']
   for row in rows:need(isinstance(row,list) and len(row)>=2 and isinstance(row[1],str) and str(uuid.UUID(row[1]))==row[1],'queue row malformed')
   if h:
    hp=h['prompt'];need(hp[1]==prompt and hp[3]['client_id']==attempt['client_id'],'history identity drift')
    s=h.get('status',{});finished=s.get('status_str')=='error' or (s.get('status_str')=='success' and s.get('completed') is True)
    if finished and not any(row[1]==prompt for row in rows):
     history_path=root/'technical-test-history.json'
     if history_path.exists():
      saved=json.loads(history_path.read_text());need(saved['prompt_id']==prompt and saved['history']==h,'persisted terminal history drift')
     else:save(history_path,{'prompt_id':prompt,'history':h,'observed_at':g.now(),'limits':g.LIMITS})
     save_matching(root/'terminal.json',{'prompt_id':prompt,'status':s,'queue_checked':True})
     # Minimal recovery is durable before optional copies/uploads. No archive tool here.
     save_matching(root/'archive-pending.json',{'state':'not_started_optional_archive','candidate_id':c['candidate_id'],'history_sha256':sha(root/'technical-test-history.json'),'next':'verify output then user-authorized async archive; no backup claim'})
     if s.get('status_str')=='success':
      try:
       if not (root/'output-verified.json').exists():save(root/'output-verified.json',g.verify_output(bsha,root,c=c))
      except Exception as e:save_matching(root/'output-verification-failed.json',{'error':str(e)})
     return
  except Exception as e:
   with (root/'observation-errors.jsonl').open('a',encoding='utf-8') as f:f.write(json.dumps({'at':g.now(),'error':str(e)})+'\n');f.flush();os.fsync(f.fileno())
  time.sleep(10)

def claim_gpu_marker(path,value):
 need(not Path(path).exists(),'unresolved GPU work marker exists; read-only reconcile, never reset')
